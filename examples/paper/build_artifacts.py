def window_keys(R: Results, code: str, model: str) -> None:
    d = study(code, model)
    alpha = d["config"]["alpha"]
    pre = code if model == "lr" else f"{code}-hgb"
    by_type: Dict[str, List[str]] = {}
    mmd_only: List[str] = []
    for wname, w in d["windows"].items():
        k = f"{pre}-{wkey(code, wname)}"
        det = detections(w)
        dg = w["diagnosis"]["final"]
        R.add(f"{k}-acc", f(w["actual_accuracy"]))
        R.add(f"{k}-dacc", pp(w["accuracy_change"]))
        R.add(f"{k}-dacc-p", pval(w["accuracy_drop_test"]["p_value"]))
        est = cbpe_estimate(w)
        R.add(f"{k}-est", f(est))
        R.add(f"{k}-esterr", pp(est - w["actual_accuracy"]))
        R.add(f"{k}-type", TYPE_LABEL[dg["drift_type"]])
        R.add(f"{k}-stage", dg["stage"])
        R.add(f"{k}-n", comma(nrows(w)))
        for name, v in det.items():
            R.add(f"{k}-{DETECTOR_KEY[name]}-p", pval(v.get("p_value")))
        for stage, sec in w["timings_seconds"].items():
            R.add(f"{k}-time-{DETECTOR_KEY.get(stage, stage.replace(' ', ''))}", f"{sec:.1f}")
        rel = w["reliability"]["summary"]
        for m in ("auroc_risk", "auroc_confidence_only", "auroc_ood"):
            R.add(f"{k}-{m.replace('_', '')}", f(rel[m]))
        if "comparison" in w:
            for est_name, err in w["comparison"]["estimate_errors"].items():
                R.add(f"{k}-err-{est_name}", pp(err))
            for meth, v in w["comparison"]["verdicts"].items():
                R.add(f"{k}-v-{meth.replace('_', '')}", TYPE_LABEL[v])
        if w["analysis_type"] != "control":
            by_type.setdefault(dg["drift_type"], []).append(wlabel(code, wname))
        if code in ("inc", "emp"):
            R.add(f"{k}-posrate", f(w["positive_rate"]))
            R.add(f"{k}-predposrate", f(w["predicted_positive_rate"]))
            R.add(f"{k}-bbse-prior", f(w["diagnosis"]["bbse"]["estimated_production_prior"][-1]))
            R.add(f"{k}-audit-drop-p", pval(w["diagnosis"]["audit_accuracy_drop_p_value"]))
            R.add(f"{k}-audit-prior-p", pval(w["diagnosis"]["audit_prior_p_value"]))
            R.add(f"{k}-audit-posrate", f(w["diagnosis"]["audit"]["audit_positive_rate"]))
            loc = w["pipelines"]["KS Test"]["localization"]
            drifted = [fd for fd in loc["feature_drifts"] if fd["drift_detected"]]
            R.add(f"{k}-ndrift", len(drifted))
            for fd in loc["feature_drifts"]:
                R.add(f"{k}-eff-{fd['feature_name'].lower()}", f(fd["score"], 3))
                share = (fd.get("distribution_shift") or {}).get("unseen_category_share")
                if share is not None:
                    R.add(f"{k}-unseen-{fd['feature_name'].lower()}", pct(share, 1))
            rca = w["pipelines"]["KS Test"].get("rca") or {}
            changes = rca.get("distribution_changes") or {}
            if changes:
                R.add(f"{k}-nsigshap", sum(v["change_significant"] for v in changes.values()))
                for feat, v in changes.items():
                    R.add(f"{k}-shap-{feat.lower()}", f"{v['change']:+.3f}")
        elif code == "gas":
            R.add(f"{k}-ndrift", w["localization"]["n_drifted_features"])
            meta = det["CBPE"]["metadata"]
            R.add(f"{k}-conf", f(meta["test_mean_confidence"]))
            R.add(f"{pre}-ref-conf", f(meta["ref_mean_confidence"])) if wkey(code, wname) == "ctrl" else None
            from drift_autopsy.stats import MIN_EXPECTED_COUNT
            cal, prod = np.asarray(meta["reference_bin_counts"]), np.asarray(meta["test_bin_counts"])
            sparse = cal < MIN_EXPECTED_COUNT
            R.add(f"{k}-sparse-share", pct(prod[sparse].sum() / prod.sum(), 0))
            R.add(f"{k}-sparse-cal-n", int(cal[sparse].sum()))
            R.add(f"{k}-audit-n", w["diagnosis"]["audit"]["n_labels"])
            sensors = w["localization"]["by_sensor"]
            R.add(f"{k}-nsensors", sum(v["n_drifted"] > 0 for v in sensors.values()))
        else:
            R.add(f"{k}-ndrift", w["localization"]["n_drifted_dimensions"])
            # covariate verdicts that rest on the multivariate test alone: no
            # single embedding dimension shifted significantly
            if dg["drift_type"] == "covariate" and w["diagnosis"]["n_input_shift_dimensions"] == 0:
                mmd_only.append(wlabel(code, wname).lstrip("b"))
    if code == "clr":
        R.add(f"{pre}-windownums-mmdonly", join(mmd_only) if mmd_only else "none")
        R.add(f"{pre}-nwindows-mmdonly", len(mmd_only))
    for t, ws in by_type.items():
        R.add(f"{pre}-windows-{t.replace('_', '')}", join(ws))
        R.add(f"{pre}-windownums-{t.replace('_', '')}", join([w.lstrip("b") for w in ws]))
        R.add(f"{pre}-nwindows-{t.replace('_', '')}", len(ws))
    for t in TYPE_LABEL:
        if t not in by_type:
            R.add(f"{pre}-windows-{t.replace('_', '')}", "none")
            R.add(f"{pre}-nwindows-{t.replace('_', '')}", 0)
    drops = [wlabel(code, k) for k, w in d["windows"].items()
             if w["analysis_type"] != "control" and w["accuracy_drop_test"]["p_value"] < alpha]
    R.add(f"{pre}-sigdrop-windows", join(drops))
    changes = [w["accuracy_change"] for w in d["windows"].values() if w["analysis_type"] != "control"]
    R.add(f"{pre}-dacc-maxabs", pp(max(abs(c) for c in changes), 1, sign=False))
    R.add(f"{pre}-nsigdrop", len(drops))
    ctrl = next(w for w in d["windows"].values() if w["analysis_type"] == "control")
    R.add(f"{pre}-ctrl-nalarms", sum(v["drift_detected"] for v in detections(ctrl).values()))
    errs = [cbpe_estimate(w) - w["actual_accuracy"] for w in d["windows"].values() if w["analysis_type"] != "control"]
    R.add(f"{pre}-esterr-max", pp(max(errs, key=abs)))
    R.add(f"{pre}-esterr-mean", pp(float(np.mean(errs))))
    R.add(f"{pre}-n-optimistic", sum(e > 0 for e in errs))


