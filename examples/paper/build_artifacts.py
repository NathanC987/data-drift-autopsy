def timelines(R: Results) -> None:
    """Measured accuracy (both models) and the CBPE estimate (LR) over the windows of the four studies."""
    plt = mpl()
    fig, axes = plt.subplots(2, 2, figsize=(6.6, 2.95))
    for ax, code in zip(axes.flat, ("inc", "emp", "gas", "clr")):
        lr, gb = study(code, "lr"), study(code, "hgb")
        names = [k for k, w in lr["windows"].items() if w["analysis_type"] in ("control", "temporal")]
        x = np.arange(len(names))
        # break lines across a missing year (no standard ACS 2020 release)
        years = [lr["windows"][k].get("year") for k in names]
        breaks = [i for i in range(1, len(names)) if years[i] and years[i - 1] and years[i] - years[i - 1] > 1]

        def series(d, fn):
            y = np.array([fn(d["windows"][k]) for k in names], dtype=float)
            xs, ys = list(x.astype(float)), list(y)
            for b in reversed(breaks):
                xs.insert(b, np.nan)
                ys.insert(b, np.nan)
            return xs, ys

        for d, color, lab in ((lr, PALETTE[0], "LR measured"), (gb, PALETTE[2], "GB measured")):
            ax.plot(*series(d, lambda w: w["actual_accuracy"]), "-o", color=color, ms=3, lw=1.3, label=lab)
        ax.plot(*series(lr, cbpe_estimate), "--s", color=PALETTE[1], ms=3, lw=1.1, mfc="white", label="LR estimate (CBPE)")
        labels = [wlabel(code, k).replace("CA ", "").replace("control", "ctrl") for k in names]
        ax.set_xticks(x, labels, rotation=45 if code in ("inc", "emp") else 0, fontsize=6)
        ax.set_title(STUDY_TITLE[code] + (" (California)" if code in ("inc", "emp") else ""), loc="left")
        ax.set_ylabel("accuracy")
    axes[0][0].legend(frameon=False, fontsize=6, loc="lower left")
    fig.tight_layout()
    save(fig, "gen_timelines")
    plt.close(fig)


