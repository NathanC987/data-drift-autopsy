def study(code: str, model: str) -> Dict[str, Any]:
    return json.loads((OUT / STUDY_FILES[(code, model)]).read_text())


def wkey(code: str, window: str) -> str:
    """Short window code for result keys: ctrl, ca2018, tx2014, b3."""
    if "held" in window:
        return "ctrl"
    if code in ("gas", "clr"):
        return "b" + window.split()[-1]
    return window.lower().replace(" ", "")


def wlabel(code: str, window: str) -> str:
    if "held" in window:
        return "control"
    if code == "gas":
        return window.replace("batch ", "b")
    if code == "clr":
        return f"b{window}"
    return window


def detections(w: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    if "pipelines" in w:
        return {n: p["detection"] for n, p in w["pipelines"].items()}
    return w["detection"]


def cbpe_estimate(w: Dict[str, Any]) -> float:
    return w["cbpe_estimated_accuracy"] if "cbpe_estimated_accuracy" in w else w["proxy"]["estimated"]["accuracy"]


def nrows(w: Dict[str, Any]) -> int:
    return int(w.get("n_rows", w.get("n_images", 0)))


def comma(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


