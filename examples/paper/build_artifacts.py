def reliability(R: Results) -> None:
    diffs, oods = [], []
    by_group: Dict[str, List[float]] = {"gas": [], "other": []}
    for code in ("inc", "emp", "gas", "clr"):
        for model in MODELS:
            d = study(code, model)
            if code == "gas":
                cal = d["config"]["split_sizes"]["calibration"]
                R.add(f"rel-gas-{model}-cal-errors", d["reliability_model"]["fusion"]["n_calibration_errors"])
                if model == "lr":
                    R.add("rel-min-events", d["reliability_model"]["fusion"]["min_events"])
                if model == "lr":
                    R.add("rel-gas-cal-n", cal)
            for w in d["windows"].values():
                s = w["reliability"]["summary"]
                if s.get("auroc_risk") is None:
                    continue
                diffs.append(s["auroc_risk"] - s["auroc_confidence_only"])
                by_group["gas" if code == "gas" else "other"].append(diffs[-1])
                oods.append(s["auroc_ood"])
    for g, v in by_group.items():
        R.add(f"rel-{g}-diff-min", f"{min(v):+.3f}")
        R.add(f"rel-{g}-diff-max", f"{max(v):+.3f}")
        R.add(f"rel-{g}-n", len(v))
    R.add("rel-nwindows", len(diffs))
    R.add("rel-fused-minus-conf-min", f"{min(diffs):+.3f}")
    R.add("rel-fused-minus-conf-max", f"{max(diffs):+.3f}")
    R.add("rel-fused-minus-conf-mean", f"{np.mean(diffs):+.3f}")
    R.add("rel-ood-auroc-min", f(min(oods)))
    R.add("rel-ood-auroc-max", f(max(oods)))
    fus = study("inc", "lr")["reliability_model"]["fusion"]
    for sig, c in fus["coefficients"].items():
        R.add(key("inc-fusion-coef", sig), f(c, 2))
    gains = []
    for code in BENCH_DATASETS:
        for model in MODELS:
            s = bench(code, "A", model)["summary"]["reliability"]
            for t, v in s.items():
                if v["auroc_risk_minus_confidence"]["mean"] is not None:
                    gains.append(v["auroc_risk_minus_confidence"]["mean"])
    R.add("rel-bench-gain-max", f"{max(gains):+.3f}")
    R.add("rel-bench-gain-min", f"{min(gains):+.3f}")


