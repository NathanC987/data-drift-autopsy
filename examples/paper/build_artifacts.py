def cam_figure(R: Results, bucket: int, k: int = 4) -> None:
    """CAMs for the k most out-of-distribution images of a bucket (data-driven selection)."""
    from threadpoolctl import threadpool_limits

    from drift_autopsy.experiments import clear10
    from drift_autopsy.rca.cam import class_activation_maps
    from drift_autopsy.reliability import OODDetector

    seed = study("clr", "lr")["config"]["seed"]          # the CLEAR-10 study's model, rebuilt exactly
    b1 = clear10.load_bucket(clear10.REFERENCE_BUCKET)
    split = clear10.split_reference(b1, seed=seed)
    names = clear10.class_names(b1)
    with threadpool_limits(limits=1):
        model = clear10.make_clear_model(random_state=seed).fit(clear10.embeddings(split.train), split.train["y_true"])
    frame = clear10.load_bucket(bucket)
    emb = clear10.embeddings(frame)
    comps = OODDetector(random_state=seed).fit(clear10.embeddings(split.train)).score_components(emb)
    ood, raw = comps["ood"], comps["ood_unclipped"]
    order = np.argsort(-raw, kind="stable")[:k]
    pred = model.predict(emb[order])
    maps = class_activation_maps(frame.iloc[order]["image_path"].tolist(), model, pred, emb[order])
    # Each map is scaled to [0, 1] within its image (standard CAM display): colors compare
    # regions inside one image, not evidence across images.
    for m in maps:
        lo, hi = float(m["cam"].min()), float(m["cam"].max())
        m["cam01"] = (m["cam"] - lo) / (hi - lo) if hi > lo else np.zeros_like(m["cam"])
    plt = mpl()
    fig, axes = plt.subplots(2, k, figsize=(1.6 * k + 0.6, 3.6), layout="constrained")
    for j, (m, i) in enumerate(zip(maps, order)):
        for row in (0, 1):
            ax = axes[row][j]
            ax.imshow(m["image"])
            if row == 1:
                ax.imshow(m["cam01"], cmap=CAM_CMAP, alpha=CAM_ALPHA, vmin=0, vmax=1)
            ax.set_xticks([])
            ax.set_yticks([])
            ax.grid(False)
            for s in ax.spines.values():
                s.set_visible(False)
        true = frame.iloc[i]["class_name"]
        axes[0][j].set_title(f"OOD {raw[i]:.1f} (unclipped)\npred: {names[int(m['target_class'])]}\ntrue: {true}",
                             fontsize=6.5, color=MUTED)
    from matplotlib.cm import ScalarMappable
    from matplotlib.colors import Normalize
    cb = fig.colorbar(ScalarMappable(norm=Normalize(0, 1), cmap=CAM_CMAP), ax=axes[1, :], ticks=[0, 1],
                      shrink=0.9, aspect=12, pad=0.02)
    cb.ax.set_yticklabels(["low", "high"], fontsize=6)
    cb.outline.set_visible(False)
    save(fig, "gen_cam")
    plt.close(fig)

    # Large single-image overlays plus a manifest for the dashboard
    cam_dir = PNG / "cam"
    cam_dir.mkdir(parents=True, exist_ok=True)
    for old in cam_dir.glob("cam_*.png"):
        old.unlink()
    manifest = {"bucket": bucket, "k": k, "colormap": CAM_CMAP, "alpha": CAM_ALPHA,
                "selection_rule": f"the {k} images of bucket {bucket} with the highest unclipped OOD score",
                "scaling": "each map scaled to [0, 1] within its own image", "images": []}
    for j, (m, i) in enumerate(zip(maps, order)):
        for kind in ("image", "overlay"):
            f, ax = plt.subplots(figsize=(3, 3))
            ax.imshow(m["image"])
            if kind == "overlay":
                ax.imshow(m["cam01"], cmap=CAM_CMAP, alpha=CAM_ALPHA, vmin=0, vmax=1)
            ax.axis("off")
            f.subplots_adjust(0, 0, 1, 1)
            f.savefig(cam_dir / f"cam_{j}_{kind}.png", dpi=110)
            plt.close(f)
        manifest["images"].append({
            "rank": j + 1, "source_image": m["image_path"], "predicted": names[int(m["target_class"])],
            "true": str(frame.iloc[i]["class_name"]), "ood_unclipped": float(raw[i]), "ood": float(ood[i]),
            "image_png": f"cam_{j}_image.png", "overlay_png": f"cam_{j}_overlay.png",
        })
    (cam_dir / "cam_manifest.json").write_text(json.dumps(manifest, indent=1))
    R.add("cam-bucket", bucket)
    R.add("cam-k", k)
    R.add("cam-nwrong", int(sum(names[int(m["target_class"])] != frame.iloc[i]["class_name"] for m, i in zip(maps, order))))



def correction(R: Results) -> None:
    """The 2026-10-15 correction of the diagnosis: simulated family-wise error of
    the old and new label-free rule, and how many benchmark verdicts changed."""
    fw = json.loads((OUT / "fwer_check.json").read_text())
    gate = max(v["gatekeeping"]["fwer"] for v in fw["results"].values())
    wh = max(v["weighted_holm"]["fwer"] for v in fw["results"].values())
    R.add("fwer-gate-pct", pct(gate, 1))
    R.add("fwer-wholm-pct", pct(wh, 1))
    R.add("fwer-alpha-pct", pct(fw["alpha"], 0))
    old = json.loads((OUT / "benchmark" / "prefix_verdicts.json").read_text())["configs"]
    changed = total = 0
    old_rates: Dict[str, List[float]] = {"A": [], "B": []}
    for cfg_key, rows in old.items():
        new = {(r["state"], r["seed"], r["mechanism"], r["intensity_label"]): r["verdicts"]["ours"]
               for r in json.loads((OUT / "benchmark" / f"{cfg_key}_runs.json").read_text())}
        for state, seed, mech, lab, _, verdict in rows:
            total += 1
            changed += new[(state, seed, mech, lab)] != verdict
        old_rates[cfg_key.split("_")[-2]].append(float(np.mean([r[5] == r[4] for r in rows])))
    R.add("fix-nchanged", comma(changed))
    R.add("fix-nwindows", comma(total))
    for design, rates in old_rates.items():
        R.add(f"fix-old-{design.lower()}-min", pct(min(rates), 1))
        R.add(f"fix-old-{design.lower()}-max", pct(max(rates), 1))


ABSTRACT_MAX_WORDS = 150        # journal rule


def flatten(anonymous: bool) -> Path:
    """Write the single-file submission (the journal accepts one .tex file).

    Inlines generated/results.tex and every generated table, checks that no
    \\input is left, that every \\res key is defined and that the abstract is
    at most ABSTRACT_MAX_WORDS words, and sets the double-blind switch."""
    import re

    paper = Path("paper")
    src = (paper / "main.tex").read_text()

    def inline(match: "re.Match[str]") -> str:
        name = match.group(1)
        path = paper / (name if name.endswith(".tex") else name + ".tex")
        body = path.read_text()
        return "% --- inlined from " + name + " ---\n" + re.sub(r"^%.*\n", "", body, count=1)

    out = re.sub(r"\\input\{([^}]+)\}", inline, src)
    if re.search(r"\\(input|include)\{", out):
        raise ValueError("an \\input survived flattening")
    switch = "\\anonymous" + ("true" if anonymous else "false") + "\n"
    out = re.sub(r"\\anonymous(true|false)\n", lambda m: switch, out, count=1)
    # resolve every \ifanonymous ... \else ... \fi in the source, so the review
    # file does not carry the names in a branch that is merely switched off
    branch = re.compile(r"(?<!\\newif)\\ifanonymous(?![a-zA-Z])(.*?)\\else(?![a-zA-Z])(.*?)\\fi(?![a-zA-Z])", re.S)
    out = branch.sub(lambda m: m.group(1 if anonymous else 2), out)
    if re.search(r"(?<!\\newif)\\ifanonymous(?![a-zA-Z])", out):
        raise ValueError("an \\ifanonymous without \\else survived flattening")
    defined = set(re.findall(r"\\csname res@([^\\]+)\\endcsname\{", out))
    code = "\n".join(line for line in out.splitlines() if not line.lstrip().startswith("%"))
    used = set(re.findall(r"\\res\{([^}]+)\}", code))
    missing = sorted(used - defined)
    if missing:
        raise ValueError(f"undefined result keys: {missing}")
    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", out, re.S).group(1)
    text = re.sub(r"\\res\{([^}]+)\}", lambda m: "0", abstract)
    words = len(re.findall(r"[A-Za-z0-9][A-Za-z0-9.,%\-]*", re.sub(r"\\[a-zA-Z]+", " ", text)))
    if words > ABSTRACT_MAX_WORDS:
        raise ValueError(f"abstract has {words} words (limit {ABSTRACT_MAX_WORDS})")
    import shutil

    sub = paper / "submission" / ("anonymous" if anonymous else "final")
    (sub / "figures").mkdir(parents=True, exist_ok=True)
    for extra in ("references.bib", "csagh.sty", "cs-agh.bst"):
        shutil.copy(paper / extra, sub / extra)
    for fig in re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", out):
        name_ = fig if fig.endswith(".pdf") else fig + ".pdf"
        shutil.copy(paper / "figures" / name_, sub / "figures" / name_)
    name = "main.tex"
    (sub / name).write_text(out)
    print(f"wrote {sub / name} ({words} abstract words, {len(used)} result keys used)")
    return sub / name


