MINUS = re.compile(r"(?<![\w{^\-\\])-(?=\d)")


def minus(text: str) -> str:
    """Typeset negative numbers with a real minus sign (valid in text and math)."""
    return MINUS.sub(r"\\nminus ", str(text))


class Results:
    """Collects \\res{key} values and writes them as one LaTeX file."""

    def __init__(self) -> None:
        self.values: Dict[str, str] = {}

    def add(self, key: str, value: Any) -> None:
        if key in self.values:
            raise KeyError(f"duplicate result key {key}")
        self.values[key] = minus(value)

    def write(self, path: Path) -> None:
        lines = [
            "% Generated by examples/paper/build_artifacts.py -- do not edit.",
            "\\providecommand{\\nminus}{\\ensuremath{-}}",
            "\\makeatletter",
            "\\DeclareRobustCommand{\\res}[1]{\\ifcsname res@#1\\endcsname\\csname res@#1\\endcsname"
            "\\else\\textbf{??#1??}\\GenericWarning{}{Undefined result #1}\\fi}",
        ]
        for k in sorted(self.values):
            lines.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{self.values[k]}}}")
        lines.append("\\makeatother")
        path.write_text("\n".join(lines) + "\n")


def f(x: float, d: int = 3) -> str:
    return f"{x:.{d}f}"


def pp(x: float, d: int = 1, sign: bool = True) -> str:
    """Proportion -> percentage points."""
    v = 100.0 * x
    if round(v, d) == 0:
        return f"{0:.{d}f}"           # no signed zero after rounding
    return f"{v:+.{d}f}" if sign else f"{v:.{d}f}"


def pct(x: float, d: int = 0) -> str:
    return f"{100.0 * x:.{d}f}"


def pval(p: float) -> str:
    """p-value for prose and tables, LaTeX math mode."""
    if p is None:
        return "--"
    if p <= 1e-300:                    # below double precision (e.g. an exact binomial tail)
        return "$<10^{-300}$"
    if p < 1e-4:
        e = int(np.floor(np.log10(p)))
        return f"$<10^{{{e + 1}}}$"
    if p < 0.001:
        return f"${p:.1e}".replace("e-0", "\\times 10^{-").replace("e-", "\\times 10^{-") + "}$"
    return f"{p:.3f}"


def ci(lo: float, hi: float, d: int = 2, scale: float = 1.0) -> str:
    return f"[{lo * scale:.{d}f}, {hi * scale:.{d}f}]"


def join(items: List[str]) -> str:
    """'a', 'a and b', 'a, b and c' (no comma before 'and')."""
    items = [str(i) for i in items]
    if not items:
        return "none"
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def alarm_macros(R: "Results", prefix: str, windows: Dict[str, Any], detections, label_of) -> None:
    """First alarm and list of alarmed windows per detector."""
    names = list(detections(next(iter(windows.values()))))
    for name in names:
        alarmed = [label_of(k) for k, w in windows.items() if detections(w)[name]["drift_detected"]
                   and label_of(k) is not None]
        short = DETECTOR_SHORT[name].lower().replace(".", "")
        R.add(f"{prefix}-alarms-{short}", join(alarmed))
        R.add(f"{prefix}-firstalarm-{short}", alarmed[0] if alarmed else "never")


def key(*parts: Any) -> str:
    return "-".join(str(p).lower().replace(" ", "").replace("_", "") for p in parts)


def write_table(name: str, body: str) -> None:
    (GEN / f"{name}.tex").write_text("% Generated by examples/paper/build_artifacts.py -- do not edit.\n"
                                     "\\providecommand{\\nminus}{\\ensuremath{-}}\n" + minus(body))


